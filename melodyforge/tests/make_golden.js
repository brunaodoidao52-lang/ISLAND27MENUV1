// Writes golden vectors (tests/golden/golden.txt) from the JS core.
// The C++ port (plugin/tests) must reproduce every value exactly.
// Run: node tests/make_golden.js
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('../core/melodyforge-core.js');

const num = x => (Number.isInteger(x) ? String(x) : x.toPrecision(17));
const FOCUS = ['balanced', 'harmony', 'rhythm', 'catchy'];

function settingsLine(s) {
    const t = s.targets;
    return ['SETTINGS', s.bars, s.populationSize, num(s.eliteRatio), num(s.mutationRate), s.maxNotesPerBar, s.melodyLow, s.melodyHigh,
            C.CHORD_RHYTHMS.indexOf(s.chordRhythm), FOCUS.indexOf(s.focus), s.key, s.scale, s.progression, s.bpm,
            s.bpmRange[0], s.bpmRange[1], +s.locks.key, +s.locks.scale, +s.locks.progression, +s.locks.bpm,
            num(t.density), num(t.stepwise), num(t.span), num(t.syncopation), num(t.repetition)].join(' ');
}
function rangesLine(s) {
    const parts = [];
    C.CONTINUOUS_GENES.forEach((g, i) => { if (s.geneRanges[g]) parts.push(i, num(s.geneRanges[g][0]), num(s.geneRanges[g][1])); });
    return ['RANGES', parts.length / 3].concat(parts).join(' ');
}
function poolsLine(s) {
    return ['POOLS', s.scalePool.length].concat(s.scalePool, [s.progressionPool.length], s.progressionPool).join(' ');
}
function genomeLine(g) {
    const ov = g.chordOverrides || [];
    return ['GENOME', g.key, g.scale, g.progression, g.bpm, g.seeds.melody, g.seeds.bass, g.seeds.chords, num(g.userScore || 0)]
        .concat(C.CONTINUOUS_GENES.map(k => num(g[k])), [ov.length], ov).join(' ');
}
function fitLine(f) { return ['FIT', num(f.total), num(f.melodic), num(f.harmonic), num(f.rhythmic)].join(' '); }

const cases = [];
const variants = [
    {},
    { bars: 8, maxNotesPerBar: 4, melodyLow: 55, melodyHigh: 76, chordRhythm: 'half', focus: 'harmony' },
    { bars: 2, maxNotesPerBar: 16, chordRhythm: 'stabs', focus: 'rhythm', targets: { density: 7, stepwise: 0.5, span: 14, syncopation: 0.4, repetition: 0.8 } },
    { bars: 6, focus: 'catchy', geneRanges: { swing: [0.4, 0.9], chordComplexity: [0.7, 1] }, bpmRange: [70, 92] },
    { key: 9, scale: 1, progression: 3, bpm: 98, locks: { key: true, scale: true, progression: true, bpm: true } },
    C.presetSettings(1, 2),                                   // Trap + Sad
    Object.assign(C.presetSettings(5, 5), { bars: 8 }),       // Funk BR + Energetic
    Object.assign(C.presetSettings(2, 6), { focus: 'catchy' }) // Lo-fi + Chill
];

let lines = ['# MelodyForge golden vectors — generated by tests/make_golden.js; do not edit'];
let caseId = 0;
variants.forEach((v, vi) => {
    const s = C.normalizeSettings(v);
    for (let k = 0; k < 8; k++) {
        const rng = C.createRng(vi * 1000 + k);
        let g = C.randomGenome(rng, s);
        if (k === 3) g = C.setChordOverride(g, 1, 5);
        if (k === 5) { g = C.cloneGenome(g); g.userScore = 0.5; }
        const p = C.render(g, s);
        const f = C.evaluate(p, g, s);
        lines.push('CASE ' + caseId++, settingsLine(s), rangesLine(s), poolsLine(s), genomeLine(g));
        for (const t of C.TRACKS) {
            lines.push(['TRACK', t, p.tracks[t].length].concat(...p.tracks[t].map(n => [n.pitch, n.start, n.length, n.velocity])).join(' '));
        }
        lines.push(['CHORDS', p.chords.length].concat(...p.chords.map(c => [c.degree, c.root, c.pcs.length, ...c.pcs, c.pitches.length, ...c.pitches])).join(' '));
        lines.push(fitLine(f));
        lines.push('MIDI ' + Buffer.from(C.toMidi(p)).toString('hex'));
        lines.push('END');
    }
});

// evolution runs
variants.forEach((v, vi) => {
    const s = C.normalizeSettings(v);
    const seed = 4242 + vi;
    let pop = C.createPopulation(s, seed);
    const gens = 6;
    for (let i = 0; i < gens; i++) pop = C.evolve(pop, s, seed * 31 + i);
    lines.push('EVOLVE ' + vi, settingsLine(s), rangesLine(s), poolsLine(s), ['RUN', seed, gens, pop.length].join(' '));
    for (const x of pop) { lines.push(genomeLine(x.genome)); lines.push(['SCORE', num(x.fitness)].join(' ')); }
    lines.push(['DIVERSITY', num(C.diversity(pop))].join(' '));
    lines.push('END');
});

// presets: every style x mood combination must produce the same settings in C++
C.STYLES.forEach((st, si) => C.MOODS.forEach((md, mi) => {
    const s = C.normalizeSettings(C.presetSettings(si, mi));
    lines.push('PRESET ' + si + ' ' + mi, settingsLine(s), rangesLine(s), poolsLine(s), 'END');
}));

const out = path.join(__dirname, 'golden', 'golden.txt');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log('wrote ' + caseId + ' render cases, ' + variants.length + ' evolution runs and ' + C.STYLES.length * C.MOODS.length +
            ' preset combinations to ' + path.relative(process.cwd(), out));
